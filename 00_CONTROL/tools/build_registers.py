def sha_of(rel):
    p = ROOT / rel
    if not p.exists():
        return None, None
    d = p.read_bytes()
    return len(d), hashlib.sha256(d).hexdigest()


def row(**kw):
    r = {"source_id": "", "document_title": "", "issuing_agency": "",
         "record_system": "", "source_identifier": "",
         "retrieval_date_utc": "", "original_url": "",
         "local_relative_path": "", "file_type": "", "file_size_bytes": "",
         "sha256_hash": "", "status": "", "verification_method": "",
         "notes": ""}
    r.update(kw)
    if r["local_relative_path"]:
        size, sha = sha_of(r["local_relative_path"])
        if size is not None:
            r["file_size_bytes"] = size
            r["sha256_hash"] = sha
    return r


